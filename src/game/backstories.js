// 무대 NPC의 백스토리 블록(프롬프트용). 해당 씬에서만 호출된다.
export function backstoryBlock(npc) {
  const b = NPC_BACKSTORY[npc]
  if (!b) return ''
  return [
    `NPC_BACKSTORY (${npc}):`,
    `  과거: ${b.past}`,
    `  동기: ${b.motive}`,
    `  비밀: ${b.secret} (쉽게 드러내지 말 것 — 신뢰(affinity)가 높을 때만 암시/고백)`,
  ].join('\n')
}
