// AI 프롬프트에 넣을 목소리 블록을 만든다 (해당 씬의 무대 NPC 것만, 토큰 절약).
export function voiceBlock(npc) {
  const v = NPC_VOICES[npc]
  if (!v) return ''
  const lines = [`NPC_VOICE (${npc}): ${v.style}`]
  if (v.examples && v.examples.length) {
    lines.push(`VOICE_EXAMPLES (${npc}): ${v.examples.map((e) => `"${e}"`).join(' / ')}`)
  }
  return lines.join('\n')
}
